// Rendering the workflow graph as a Mermaid flowchart and as graph.md.

const esc = (s) => String(s).replace(/"/g, "#quot;").replace(/\|/g, "#124;");
const safe = (id) => id.replace(/-/g, "_");
const shorten = (s, n) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n - 1) > 0 ? s.lastIndexOf(" ", n - 1) : n - 1) + "…");
const promoLabel = (p) => p.replace("->", " → ");

export function toMermaid(result) {
  const out = ["flowchart TD", "  router([router])"];
  const label = (n) => esc(n.promotes ? `${n.title} (${promoLabel(n.promotes)})` : n.title);
  const shape = (n) => (n.kind === "gate" ? `{{"${label(n)}"}}` : n.kind === "service" ? `[/"${label(n)}"/]` : `["${label(n)}"]`);
  for (const n of result.nodes) out.push(`  ${safe(n.id)}${shape(n)}`);
  if (result.edges.some((e) => e.to === "end")) out.push("  end_((end))");
  for (const id of result.entries) out.push(`  router --> ${safe(id)}`);
  for (const e of result.edges) {
    out.push(`  ${safe(e.from)} -->|"${esc(shorten(String(e.when), 48))}"| ${e.to === "end" ? "end_" : safe(e.to)}`);
  }
  const byLife = { throwaway: [], tracer: [], hardened: [] };
  for (const n of result.nodes) if (byLife[n.lifecycle]) byLife[n.lifecycle].push(safe(n.id));
  out.push("  classDef throwaway fill:#fde68a,stroke:#b45309,color:#000");
  out.push("  classDef tracer fill:#bfdbfe,stroke:#1d4ed8,color:#000");
  out.push("  classDef hardened fill:#bbf7d0,stroke:#15803d,color:#000");
  for (const [k, ids] of Object.entries(byLife)) if (ids.length) out.push(`  class ${ids.join(",")} ${k}`);
  return out.join("\n");
}

export function graphMarkdown(result, name) {
  const kind = (n) => (n.promotes ? `gate (${promoLabel(n.promotes)})` : n.kind);
  const rows = result.nodes.map((n) => `| [${n.id}](playbooks/${n.id}.md) | ${kind(n)} | ${n.phase} | ${n.lifecycle} | ${n.exits.map((e) => e.to).join(", ") || "-"} |`);
  return [
    `# ${name} workflow graph`,
    "",
    "Generated by `vajra/scripts/validate.mjs --write-graph`. Do not edit by hand; edit playbook frontmatter and regenerate.",
    "",
    "```mermaid",
    toMermaid(result),
    "```",
    "",
    "| Playbook | Kind | Phase | Lifecycle | Exits to |",
    "|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}
